"""The deterministic metamorphic campaign report (JSON and markdown) with denominators.

Unit conventions: a *pair* is one applicable (scenario, operator) combination, counted once. A relation is *checked* once per pair it applies to;
it *held* if it was not violated; it was *exercised* (non-vacuous) if the mutation changed the verdict or codes of that pair. Nothing here is an
accuracy figure: the report states that the engine obeys the written invariants on controlled synthetic mutations."""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path
from typing import Optional

from tests.analysis_eval import DEFAULT_OUT
from tests.metamorphic.campaign import run_campaign
from tests.metamorphic.operators import OPERATORS
from tests.metamorphic.scenarios import all_scenarios

JSON_NAME, MD_NAME = "metamorphic_report.json", "metamorphic_report.md"


def build() -> dict:
    scenarios = all_scenarios()
    bases, pairs = run_campaign(scenarios, OPERATORS)
    assert len({(p.scenario_id, p.op_id) for p in pairs}) == len(pairs)
    relation_stats: dict[str, Counter] = {}
    for pair in pairs:
        for relation in pair.relations:
            stats = relation_stats.setdefault(relation.relation, Counter())
            stats["checked"] += 1
            stats["held"] += relation.holds
            stats["violated"] += not relation.holds
            stats["exercised"] += bool(pair.changed)
    for base in bases:
        for relation in base.relations:
            stats = relation_stats.setdefault(relation.relation, Counter())
            stats["checked"] += 1
            stats["held"] += relation.holds
            stats["violated"] += not relation.holds
    operator_rows = {}
    for operator in OPERATORS:
        own = [p for p in pairs if p.op_id == operator.op_id]
        transitions = Counter(f"{p.base.verdict} -> {p.mutant.verdict or p.mutant.kind}" for p in own)
        operator_rows[operator.op_id] = {
            "kind": operator.kind, "description": operator.description, "pairs": len(own), "changed_verdict_or_codes": sum(p.changed for p in own),
            "transitions": dict(sorted(transitions.items())), "violations": sum(bool(p.violations) for p in own),
        }
    report = {
        "kind": "metamorphic-campaign-report",
        "disclaimer": ("Controlled synthetic mutations through the public evaluation entry point; relations are the specification's invariants M-1..M-6. "
                       "The report shows the engine obeys them on these mutations; it is not an accuracy measurement and says nothing about real SBOMs."),
        "scenarios": {"count": len(scenarios), "by_predicate": dict(sorted(Counter(s.predicate for s in scenarios).items())),
                      "by_format": dict(sorted(Counter(s.sbom_format for s in scenarios).items())),
                      "base_verdicts": {b.scenario_id: b.observation.verdict for b in bases}},
        "operators": {"count": len(OPERATORS), "by_kind": dict(sorted(Counter(o.kind for o in OPERATORS).items()))},
        "pairs": {"count": len(pairs), "by_kind": dict(sorted(Counter(p.kind for p in pairs).items())),
                  "verdict_changed_or_codes_changed": sum(p.changed for p in pairs),
                  "mutant_without_verdict": dict(sorted(Counter(p.mutant.kind for p in pairs if p.mutant.kind != "evaluated").items()))},
        "relations": {k: dict(sorted(v.items())) for k, v in sorted(relation_stats.items())},
        "violations": [{"scenario": p.scenario_id, "operator": p.op_id, "relations": [r.relation for r in p.violations]} for p in pairs if p.violations],
        "operators_that_never_changed_a_verdict_or_codes": sorted(o for o, row in operator_rows.items() if row["changed_verdict_or_codes"] == 0),
        "operator_table": operator_rows,
    }
    return report


def render_json(report: dict) -> str:
    return json.dumps(report, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def render_markdown(report: dict) -> str:
    s, o, p = report["scenarios"], report["operators"], report["pairs"]
    lines = ["# Metamorphic campaign report (generated by `python -m tests.metamorphic`)", "", report["disclaimer"], "",
             f"* Scenarios: **{s['count']}** (by predicate {s['by_predicate']}, by SBOM format {s['by_format']}); base verdicts {s['base_verdicts']}.",
             f"* Operators: **{o['count']}** ({o['by_kind']}).",
             f"* Pairs (applicable scenario x operator, each counted once): **{p['count']}** ({p['by_kind']}); the mutation changed the verdict or codes in "
             f"{p['verdict_changed_or_codes_changed']}; mutants without a verdict: {p['mutant_without_verdict'] or 'none'}.",
             f"* Violations: **{len(report['violations'])}**.", "", "## Relations", "",
             "| Relation | Checked | Held | Violated | Exercised (mutation changed the outcome) |", "|---|---|---|---|---|"]
    for name, stats in report["relations"].items():
        lines.append(f"| {name} | {stats.get('checked', 0)} | {stats.get('held', 0)} | {stats.get('violated', 0)} | {stats.get('exercised', 0)} |")
    lines += ["", "M-1 degrading never raises a verdict; M-2 deleting never creates an Absent state; M-3 determinism; M-4 an injected positive observation gives "
              "Insufficient; M-5 every triggered rule is in the rationale; M-6 free text never changes the verdict.",
              "", "## Operators", "", "| Operator | Kind | Pairs | Changed | Verdict transitions |", "|---|---|---|---|---|"]
    for op_id, row in report["operator_table"].items():
        transitions = "; ".join(f"{k} x{v}" for k, v in row["transitions"].items())
        lines.append(f"| {op_id} | {row['kind']} | {row['pairs']} | {row['changed_verdict_or_codes']} | {transitions} |")
    lines += ["", "Operators that never changed a verdict or the codes (inert on these scenarios, kept for the record): "
              + (", ".join(report["operators_that_never_changed_a_verdict_or_codes"]) or "none") + "."]
    return "\n".join(lines) + "\n"


def main(argv: Optional[list[str]] = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    out = Path(args[args.index("--out") + 1]) if "--out" in args else DEFAULT_OUT
    report = build()
    text_json, text_md = render_json(report), render_markdown(report)
    clean = not report["violations"]
    if "--check" in args:
        stale = [n for n, t in ((JSON_NAME, text_json), (MD_NAME, text_md)) if not (out / n).is_file() or (out / n).read_text(encoding="utf-8") != t]
        if stale:
            print(f"STALE: {', '.join(stale)}")
            return 1
        return 0 if clean else 1
    out.mkdir(parents=True, exist_ok=True)
    (out / JSON_NAME).write_text(text_json, encoding="utf-8")
    (out / MD_NAME).write_text(text_md, encoding="utf-8")
    print(text_md)
    return 0 if clean else 1


if __name__ == "__main__":
    sys.exit(main())
