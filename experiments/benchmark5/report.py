"""Render RESULTS.md from scanner_results.json and ours_results.json (no recomputation of any metric here)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
S = json.loads((HERE / "scanner_results.json").read_text())
O = json.loads((HERE / "ours_results.json").read_text())
ORACLE = json.loads((HERE / "oracle_raw.json").read_text())


def pct(x):
    return "n/a" if x != x else f"{100 * x:.1f}%"


def ci(pair):
    return "n/a" if pair[0] != pair[0] else f"[{100 * pair[0]:.1f}, {100 * pair[1]:.1f}]"


def metrics(c):
    tp, fp, tn, fn = c["TP"], c["FP"] + c.get("unmapped", 0), c["TN"], c["FN"]
    n = tp + fp + tn + fn
    p = tp / (tp + fp) if tp + fp else float("nan")
    r = tp / (tp + fn) if tp + fn else float("nan")
    a = (tp + tn) / n if n else float("nan")
    f1 = 2 * p * r / (p + r) if p == p and r == r and p + r else float("nan")
    return p, r, a, f1


lines = ["# Benchmark: five constructed projects (47 components) — scanners and this repository's tool", "",
         "Generated by `report.py` from `scanner_results.json` and `ours_results.json`. Method and limits: see `README.md` in this directory.", "",
         "## 1. Vulnerability scanners (task: which advisories affect the pinned component versions?)", "",
         "Unit = (component, advisory group). Oracle = OSV snapshot + own version-range evaluation. TP/FP/TN/FN as defined in `score_scanners.py`; "
         "universe per component = every OSV advisory naming that package (any version). Coverage: Trivy and OSV-Scanner scanned the SBOMs "
         "(all 47 components, 3 ecosystems); pip-audit scanned only the PyPI requirement files; npm audit only the npm lockfiles; **Grype could not run** "
         "(its database host `grype.anchore.io` returns 403 in this environment).", "",
         "| Tool | Scope | TP | FP | TN | FN | Precision | Recall | Accuracy | F1 | Recall 95% CI (Wilson) |", "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
INV = json.loads((HERE / "inventory_truth.json").read_text())
count = lambda eco: sum(len(c.get(eco, {})) for c in INV.values())
scope = {"Trivy": "SBOM, 47 comps", "OSV-Scanner": "SBOM, 47 comps", "pip-audit": f"requirements, {count('pypi')} PyPI comps", "npm audit": f"lockfiles, {count('npm')} npm comps"}
for row in S["rows"]:
    t = row["total"]
    p, r, a, f1 = metrics(t)
    lines.append(f"| {row['tool']} | {scope[row['tool']]} | {t['TP']} | {t['FP'] + t['unmapped']} | {t['TN']} | {t['FN']} | {pct(p)} | {pct(r)} | {pct(a)} | {pct(f1)} | {ci(row['metrics']['recall_ci'])} |")
lines += ["| Grype 0.121.0 | — | — | — | — | — | blocked | blocked | blocked | blocked | — |", ""]
lines += ["### Per project (TP / FP / TN / FN)", "", "| Tool | " + " | ".join(sorted({p for r in S['rows'] for p in r['per_project']})) + " |", "|---|" + "---|" * len({p for r in S['rows'] for p in r['per_project']})]
projects = sorted({p for r in S["rows"] for p in r["per_project"]})
for row in S["rows"]:
    cells = []
    for p in projects:
        c = row["per_project"].get(p)
        cells.append("—" if not c else f"{c['TP']} / {c['FP'] + c['unmapped']} / {c['TN']} / {c['FN']}")
    lines.append(f"| {row['tool']} | " + " | ".join(cells) + " |")
lines += ["", f"Oracle positives (affected component/advisory-group pairs, excluding disputed): {S['rows'][1]['total']['TP'] + S['rows'][1]['total']['FN']}; "
          f"disputed (excluded): {S['rows'][1]['total']['disputed']} (Pillow 8.1.0 / PYSEC-2022-42980: version list says affected, ECOSYSTEM range says not).", "",
          "### Findings the scanners missed (false negatives vs. oracle)", "", "| Tool | Project | Component | Advisory ids |", "|---|---|---|---|"]
for m in S["missed"]:
    lines.append(f"| {m['tool']} | {m['project']} | {m['component']} | {', '.join(m['advisory'][:3])} |")
lines += ["", "Adjudicated: Trivy reports `NSWG-ECO-516` for lodash 4.17.15, which the oracle does not alias; it is the same issue as CVE-2020-8203 / GHSA-p6mc-m468-83gw "
          "(same HackerOne report 712065, fixed in 4.17.19) and is treated as a duplicate of an already-counted true positive, not as a false positive.", ""]

n_true = sum(1 for r in O["rows"] if r["variant"] == "A" and r["truth"] == "true")
n_other = sum(1 for r in O["rows"] if r["variant"] == "A" and r["stratum"] == "same_package_other_version")
n_false = sum(1 for r in O["rows"] if r["variant"] == "A" and r["truth"] == "false")
lines += ["## 2. This repository's evidence tool (task: accept or reject `component_not_present` VEX claims)", "",
          f"Different task, not comparable to section 1: the tool does not detect vulnerabilities. {n_true + n_false} claims per variant = {n_false} false claims (component *is* in the SBOM) + "
          f"{n_true} true claims (component from another project, {n_other} of them the same package at a different version). Positive class = verdict `Supported`.", "",
          "| Evidence variant | TP | FP | TN | FN | Precision | Recall | Accuracy | Verdicts on true claims |", "|---|---:|---:|---:|---:|---:|---:|---:|---|"]
names = {"A": "A. flat SBOM only", "B": "B. + full_component_list assertion (P2)", "C": "C. + flat composition `complete`",
         "D": "D. nested layout + `complete` + assertion", "E": "E. D + verification result (synthetic)"}
for v, s in O["summary"].items():
    p, r, a, f1 = metrics(s)
    true_verdicts = sorted(k for k in s["verdicts"] if "'true'" in k)
    lines.append(f"| {names[v]} | {s['TP']} | {s['FP']} | {s['TN']} | {s['FN']} | {pct(p)} | {pct(r)} | {pct(a)} | {', '.join(k.replace(chr(40) + chr(39) + 'true' + chr(39) + ', ', '').rstrip(')') + ' ×' + str(s['verdicts'][k]) for k in true_verdicts)} |")
lines += ["", "Every false claim is `Insufficient` with code `CLAIM_CONTRADICTED_BY_INVENTORY` in all variants (FP = 0)."]
(HERE / "RESULTS.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines[:22]))
